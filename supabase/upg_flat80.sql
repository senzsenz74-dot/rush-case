-- =====================================================================
-- RUSH CASE — апгрейд: возврат 80% на всех множителях ×1,05–×5 (убрана «льгота» 92% на ×1,05–×1,3 и плавный спуск
-- до ×1,5 — на мелких множителях баланс накатывался слишком легко). Выше ×5 — без изменений.
-- Запуск: Supabase → SQL Editor → вставить весь файл → Run. Повторный запуск безопасен. Сайт показывает тот же шанс (js/app.js upgRtp).
-- =====================================================================
create or replace function public._upg_rtp(x numeric) returns numeric language sql immutable as $$
  select case when x <= 5 then 0.80
              when x < 6 then 0.80 + (x - 5) * 0.12
              else 0.92 end
$$;

select 'апгрейд: шанс на ×1.1 — ' || round(least(0.75, public._upg_rtp(1.1) / 1.1) * 100, 1) || '%, на ×1.3 — ' || round(public._upg_rtp(1.3) / 1.3 * 100, 1)
  || '%, на ×1.5 — ' || round(public._upg_rtp(1.5) / 1.5 * 100, 1) || '%' as result;
